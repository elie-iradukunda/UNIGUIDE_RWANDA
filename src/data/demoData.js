export const findEquipmentById = (id) => {
  const key = String(id || '').toLowerCase();
  return equipmentItems.find((item) => (
    String(item.id).toLowerCase() === key ||
    String(item.assetTag).toLowerCase() === key ||
    String(item.assetTag).toLowerCase().replace('-', '') === key
  ));
};
